function measurements = build_classifier_measurements(epoch)
% Canonical 13-column observation contract for the classifier TC adapter:
% rho, rho_dot, satellite XYZ, satellite velocity XYZ, PRN, Type,
% stored Uncertainty (unused by adapter), CNR, elevation.
n = size(epoch{10},1);
assert(size(epoch{11},1) == n && size(epoch{9},1) == n && ...
    numel(epoch{15}) == n && numel(epoch{16}) == n, ...
    'classifier:MisalignedRows', 'Epoch arrays must have the same satellite ordering and row count.');
measurements = [epoch{10}(:,2), -epoch{11}(:,1).*epoch{11}(:,5), ...
    epoch{10}(:,3:5), epoch{11}(:,2:4), epoch{10}(:,1), ...
    epoch{15}(:), epoch{16}(:), epoch{9}(:,1:2)];
assert(size(measurements,2) == 13, 'classifier:ObservationWidth', ...
    'Expected the documented 13-column observation contract.');
end
